/**
 * Quy tắc phân loại giao dịch sổ cái: loại nào tăng nợ, loại nào giảm nợ, loại nào
 * bị khoá bởi kỳ đã ký. Mọi truy vấn SQL phải dùng fragment ở đây thay vì tự chép
 * literal loại giao dịch — thêm loại mới chỉ sửa một chỗ.
 *
 * Quy ước:
 *  - lay_hang, thue_hd: tăng nợ (cột Lấy hàng / Phát sinh).
 *  - thanh_toan: giảm nợ (cột Trả / Đã trả).
 *  - dieu_chinh: dương → phát sinh, âm → đã trả; không bị khoá kỳ (lối thoát).
 */

import { Prisma } from "@prisma/client";

export const TRANSACTION_TYPES = ["lay_hang", "thue_hd", "thanh_toan", "dieu_chinh"] as const;
export type TransactionType = (typeof TRANSACTION_TYPES)[number];

export const TRANSACTION_TYPE_LABELS: Record<TransactionType, string> = {
  lay_hang: "Lấy hàng",
  thue_hd: "Thuế hoá đơn",
  thanh_toan: "Thanh toán",
  dieu_chinh: "Điều chỉnh",
};

/** Loại làm tăng nợ (luôn dương). */
export const DEBT_INCREASE_TYPES = ["lay_hang", "thue_hd"] as const satisfies readonly TransactionType[];

/** Loại bị khoá khi rơi vào kỳ NCC đã ký đối chiếu. `dieu_chinh` cố ý không nằm đây. */
export const PERIOD_LOCKED_TYPES = ["lay_hang", "thue_hd", "thanh_toan"] as const satisfies readonly TransactionType[];

export function isPeriodLockedType(type: string): boolean {
  return (PERIOD_LOCKED_TYPES as readonly string[]).includes(type);
}

type AutoGeneratedRow = { paymentRoundItemId?: number | null; deliveryId?: number | null };

/** Dòng tự sinh (từ đợt thanh toán / phiếu ngày) — không cho sửa/xoá tay. */
export const AUTO_GENERATED_GUARD = {
  message: "Dòng này được sinh tự động từ đợt thanh toán hoặc phiếu vật tư ngày, không sửa/xoá tay",
  isAutoGenerated(row: AutoGeneratedRow): boolean {
    return row.paymentRoundItemId != null || row.deliveryId != null;
  },
  assertManualEditable(row: AutoGeneratedRow): void {
    if (row.paymentRoundItemId != null || row.deliveryId != null) {
      throw new Error(AUTO_GENERATED_GUARD.message);
    }
  },
};

const AMOUNT_COLUMNS: readonly string[] = ["totalTt", "totalHd"];

/** Whitelist cột số tiền — không bao giờ nội suy chuỗi ngoài danh sách. */
function columnSql(col: string): Prisma.Sql {
  if (!AMOUNT_COLUMNS.includes(col)) {
    throw new Error(`Cột số tiền không hợp lệ: ${col}`);
  }
  return Prisma.raw(`"${col}"`);
}

/** `"transactionType" IN ('lay_hang','thue_hd')` — chỉ nhận literal thuộc TRANSACTION_TYPES. */
export function typeInSql(types: readonly TransactionType[]): Prisma.Sql {
  if (types.length === 0) throw new Error("typeInSql cần ít nhất một loại giao dịch");
  const literals = types.map((t) => {
    if (!(TRANSACTION_TYPES as readonly string[]).includes(t)) {
      throw new Error(`Loại giao dịch không hợp lệ: ${t}`);
    }
    return `'${t}'`;
  });
  return Prisma.raw(`"transactionType" IN (${literals.join(",")})`);
}

/** Biểu thức CASE: phần làm tăng nợ (>= 0) của một dòng. */
export function increaseSql(col: "totalTt" | "totalHd"): Prisma.Sql {
  const c = columnSql(col);
  return Prisma.sql`CASE
    WHEN ${typeInSql(DEBT_INCREASE_TYPES)} THEN ${c}
    WHEN "transactionType" = 'dieu_chinh' AND ${c} > 0 THEN ${c}
    ELSE 0 END`;
}

/**
 * Biểu thức CASE: số dư có dấu của một dòng (thanh_toan âm, mọi loại khác dương —
 * kể cả dieu_chinh, vốn đã mang dấu riêng). Dùng cho số dư lũy kế / đầu kỳ.
 */
export function signedSql(col: "totalTt" | "totalHd"): Prisma.Sql {
  const c = columnSql(col);
  return Prisma.sql`CASE WHEN "transactionType" = 'thanh_toan' THEN -${c} ELSE ${c} END`;
}

/** Biểu thức CASE: phần làm giảm nợ (>= 0) của một dòng. */
export function decreaseSql(col: "totalTt" | "totalHd"): Prisma.Sql {
  const c = columnSql(col);
  return Prisma.sql`CASE
    WHEN "transactionType" = 'thanh_toan' THEN ${c}
    WHEN "transactionType" = 'dieu_chinh' AND ${c} < 0 THEN -${c}
    ELSE 0 END`;
}
